#!/usr/bin/env python3
"""
Parses Callgrind output files generated by `cargo bench --bench in_memory_workload`
and generates ASCII or Markdown breakdowns of per-method exclusive (self) and inclusive instruction costs,
or traces the callers / call sites of any specified function.

Supports both single-run profiling and baseline comparison mode:
  ./scripts/profile_callgrind.py                          # Top functions by Self and Inclusive Ir (ASCII)
  ./scripts/profile_callgrind.py --markdown               # Print Markdown formatted report
  ./scripts/profile_callgrind.py --output report.md       # Write Markdown report to file
  ./scripts/profile_callgrind.py --baseline base          # Compare against baseline (ASCII)
  ./scripts/profile_callgrind.py --baseline base -m       # Compare against baseline (Markdown)
  ./scripts/profile_callgrind.py --callers <pattern>      # Show who called matching functions
  ./scripts/profile_callgrind.py <path-to-callgrind.out>  # Custom input file
"""

import argparse
import os
import re
import sys

def demangle(name):
    if not name or name.startswith('0x'):
        return name
    name = re.sub(r'::h[0-9a-f]{16}$', '', name)
    return name

def find_callgrind_file(baseline=None):
    if baseline and os.path.isfile(baseline):
        return baseline
    base_dir = 'target/iai/appendfs/in_memory_workload'
    if not os.path.exists(base_dir):
        return None
    candidates = []
    suffix = f".{baseline}@{baseline}" if baseline else None
    for root, _, files in os.walk(base_dir):
        for f in files:
            if not f.startswith('callgrind.'):
                continue
            if baseline:
                if not (f.endswith(suffix) or f"@{baseline}" in f or f".{baseline}@" in f):
                    continue
            else:
                if '@' in f or f.endswith('.old'):
                    continue
            if '.t1.p1.out' in f or ('.out' in f and '.p' not in f):
                full_path = os.path.join(root, f)
                size = os.path.getsize(full_path)
                mtime = os.path.getmtime(full_path)
                candidates.append((mtime, size, full_path))
    if not candidates:
        return None
    candidates.sort(key=lambda x: (x[0], x[1]), reverse=True)
    return candidates[0][2]

def parse_callgrind(filename):
    if not os.path.exists(filename):
        print(f"Error: file not found: {filename}", file=sys.stderr)
        sys.exit(1)

    fn_map = {}        # fid -> name
    self_cost = {}     # fn -> exclusive ir
    call_cost = {}     # caller -> sum of call site ir
    call_counts = {}   # callee -> count
    callers_map = {}   # callee -> { caller: {'calls': N, 'ir': Ir} }
    
    current_fn = None
    last_callee = None
    last_calls = 0
    total_ir = 0

    with open(filename, 'r') as f:
        for line in f:
            line = line.strip()
            if line.startswith('summary:'):
                total_ir = int(line.split()[1])
            elif line.startswith('fn='):
                val = line[3:]
                if '(' in val and ')' in val:
                    fid = val[val.find('(')+1:val.find(')')]
                    name = val[val.find(')')+1:].strip()
                    if name:
                        fn_map[fid] = name
                    current_fn = fn_map.get(fid, name or fid)
                else:
                    current_fn = val
                last_callee = None
                last_calls = 0
            elif line.startswith('cfn='):
                val = line[4:]
                if '(' in val and ')' in val:
                    fid = val[val.find('(')+1:val.find(')')]
                    name = val[val.find(')')+1:].strip()
                    if name:
                        fn_map[fid] = name
                    last_callee = fn_map.get(fid, name or fid)
                else:
                    last_callee = val
            elif line.startswith('calls='):
                parts = line.split()
                try:
                    last_calls = int(parts[0].split('=')[1])
                    if last_callee:
                        call_counts[last_callee] = call_counts.get(last_callee, 0) + last_calls
                except (ValueError, IndexError):
                    last_calls = 0
            elif line and line[0].isdigit():
                parts = line.split()
                if len(parts) >= 2 and current_fn:
                    try:
                        ir = int(parts[1])
                        if last_callee and last_calls > 0:
                            call_cost[current_fn] = call_cost.get(current_fn, 0) + ir
                            c_dict = callers_map.setdefault(last_callee, {})
                            entry = c_dict.setdefault(current_fn, {'calls': 0, 'ir': 0})
                            entry['calls'] += last_calls
                            entry['ir'] += ir
                        else:
                            self_cost[current_fn] = self_cost.get(current_fn, 0) + ir
                    except ValueError:
                        pass
                last_callee = None
                last_calls = 0

    return total_ir, self_cost, call_cost, call_counts, callers_map

def filter_overview_rows(self_cost, call_cost, call_counts):
    all_fns = set(self_cost.keys()) | set(call_cost.keys())
    rows = []
    skip_prefixes = (
        'below main',
        'std::rt::lang_start',
        '__libc_start_main',
        'in_memory_workload::in_memory_fs_group::__run',
        'in_memory_workload::main',
        'in_memory_workload::bench_mixed_workload::wrapper',
        'in_memory_workload::bench_mixed_workload::__iai_callgrind_wrapper',
    )
    skip_exact = {'main', ', ()>', '>::{closure#0}'}

    for fn in all_fns:
        if any(fn.startswith(p) for p in skip_prefixes) or fn in skip_exact:
            continue
        s = self_cost.get(fn, 0)
        c = call_cost.get(fn, 0)
        incl = s + c
        calls = call_counts.get(fn, 0)
        clean_name = demangle(fn)
        rows.append((clean_name, s, incl, calls))
    return rows

def extract_flush_calls(call_counts):
    return (
        call_counts.get('<appendfs::fs::InMemoryFS>::run_flush_cycle', 0)
        or call_counts.get('<appendfs::fs::InMemoryFS>::quiesce', 0)
        or call_counts.get('<appendfs::fs::InMemoryFS>::flush_log', 0)
    )

def extract_subsystem_ir(callers_map, pattern):
    matched = [fn for fn in callers_map if pattern.lower() in fn.lower()]
    return sum(sum(d['ir'] for d in callers_map[fn].values()) for fn in matched)

def format_overview_ascii(total_ir, self_cost, call_cost, call_counts, filename):
    rows = filter_overview_rows(self_cost, call_cost, call_counts)
    flush_calls = extract_flush_calls(call_counts)

    out = []
    out.append(f"\nProfile source: {filename}")
    out.append(f"Total instructions executed: {total_ir:,}")
    out.append(f"Flushes executed: {flush_calls}")
    out.append("=" * 100)

    # Top 25 by Self
    rows_by_self = sorted(rows, key=lambda x: x[1], reverse=True)
    out.append("\n--- TOP 25 FUNCTIONS BY EXCLUSIVE (SELF) INSTRUCTIONS ---")
    out.append(f"{'Self %':>7}  {'Self Ir':>14}  {'Incl %':>7}  {'Incl Ir':>14}  {'Calls':>8}  Function")
    out.append("-" * 100)
    for fn, s, incl, calls in rows_by_self[:25]:
        s_pct = (s / total_ir) * 100 if total_ir else 0
        i_pct = (incl / total_ir) * 100 if total_ir else 0
        calls_str = f"{calls:,}" if calls > 0 else "-"
        out.append(f"{s_pct:6.2f}%  {s:14,}  {i_pct:6.2f}%  {incl:14,}  {calls_str:>8}  {fn[:45]}")

    # Top 20 by Inclusive
    rows_by_incl = sorted(rows, key=lambda x: x[2], reverse=True)
    out.append("\n--- TOP 20 FUNCTIONS BY INCLUSIVE INSTRUCTIONS ---")
    out.append(f"{'Incl %':>7}  {'Incl Ir':>14}  {'Self %':>7}  {'Self Ir':>14}  {'Calls':>8}  Function")
    out.append("-" * 100)
    for fn, s, incl, calls in rows_by_incl[:20]:
        s_pct = (s / total_ir) * 100 if total_ir else 0
        i_pct = (incl / total_ir) * 100 if total_ir else 0
        calls_str = f"{calls:,}" if calls > 0 else "-"
        out.append(f"{i_pct:6.2f}%  {incl:14,}  {s_pct:6.2f}%  {s:14,}  {calls_str:>8}  {fn[:45]}")
    out.append("")
    return "\n".join(out)

def format_overview_markdown(total_ir, self_cost, call_cost, call_counts, filename, callers_map=None):
    rows = filter_overview_rows(self_cost, call_cost, call_counts)
    flush_calls = extract_flush_calls(call_counts)
    base_filename = os.path.basename(filename)

    lines = []
    lines.append("# ⚡ AppendFS Benchmark & Instruction Profiling Report\n")
    lines.append("> [!NOTE]")
    lines.append("> This deterministic benchmark measures exact CPU instruction execution counts (`Ir`) and call graph statistics using `iai-callgrind` and Valgrind's Callgrind tool. The workload executes entirely in-memory with zero wall-clock timer variance.\n")
    lines.append("## 📊 Summary Metrics\n")
    lines.append("| Metric | Value |")
    lines.append("| :--- | :--- |")
    lines.append(f"| **Total Instructions (`Ir`)** | **`{total_ir:,}`** |")
    lines.append(f"| **Flushes Executed** | **`{flush_calls}`** |")
    lines.append(f"| **Profile Source** | `{base_filename}` |\n")

    # Top 25 by Self
    rows_by_self = sorted(rows, key=lambda x: x[1], reverse=True)
    lines.append("## 🎯 Top 25 Functions by Exclusive (Self) Instructions\n")
    lines.append("| Rank | Function | Self Ir | Self % | Incl Ir | Incl % | Calls |")
    lines.append("| :---: | :--- | :---: | :---: | :---: | :---: | :---: |")
    for rank, (fn, s, incl, calls) in enumerate(rows_by_self[:25], 1):
        s_pct = (s / total_ir) * 100 if total_ir else 0
        i_pct = (incl / total_ir) * 100 if total_ir else 0
        calls_str = f"`{calls:,}`" if calls > 0 else "-"
        fn_escaped = fn.replace("|", "\\|")
        lines.append(f"| {rank} | `{fn_escaped}` | `{s:,}` | {s_pct:.2f}% | `{incl:,}` | {i_pct:.2f}% | {calls_str} |")
    lines.append("")

    # Top 20 by Inclusive
    rows_by_incl = sorted(rows, key=lambda x: x[2], reverse=True)
    lines.append("## 🌳 Top 20 Functions by Inclusive Instructions\n")
    lines.append("| Rank | Function | Incl Ir | Incl % | Self Ir | Self % | Calls |")
    lines.append("| :---: | :--- | :---: | :---: | :---: | :---: | :---: |")
    for rank, (fn, s, incl, calls) in enumerate(rows_by_incl[:20], 1):
        s_pct = (s / total_ir) * 100 if total_ir else 0
        i_pct = (incl / total_ir) * 100 if total_ir else 0
        calls_str = f"`{calls:,}`" if calls > 0 else "-"
        fn_escaped = fn.replace("|", "\\|")
        lines.append(f"| {rank} | `{fn_escaped}` | `{incl:,}` | {i_pct:.2f}% | `{s:,}` | {s_pct:.2f}% | {calls_str} |")
    lines.append("")

    if callers_map:
        lines.append("## 🔍 Memory Subsystem Callers\n")
        for target_pattern, title in [("memcpy", "Memory Copy (`memcpy`) Callers"), ("memset", "Memory Zeroing (`memset`) Callers")]:
            callers_md = format_callers_markdown(callers_map, target_pattern, total_ir)
            if callers_md:
                lines.append(f"<details>\n<summary><b>{title}</b></summary>\n")
                lines.append(callers_md)
                lines.append("</details>\n")

    return "\n".join(lines)

def compute_function_diffs(b_self, b_call, b_counts, p_self, p_call, p_counts):
    skip_prefixes = (
        'below main',
        'std::rt::lang_start',
        '__libc_start_main',
        'in_memory_workload::in_memory_fs_group::__run',
        'in_memory_workload::main',
        'in_memory_workload::bench_mixed_workload::wrapper',
        'in_memory_workload::bench_mixed_workload::__iai_callgrind_wrapper',
    )
    skip_exact = {'main', ', ()>', '>::{closure#0}'}

    all_fns = set(b_self.keys()) | set(p_self.keys())
    diff_rows = []
    for fn in all_fns:
        if any(fn.startswith(p) for p in skip_prefixes) or fn in skip_exact:
            continue
        bs = b_self.get(fn, 0)
        ps = p_self.get(fn, 0)
        d = ps - bs
        clean = demangle(fn)
        b_incl = bs + b_call.get(fn, 0)
        p_incl = ps + p_call.get(fn, 0)
        b_calls = b_counts.get(fn, 0)
        p_calls = p_counts.get(fn, 0)
        diff_rows.append({
            'name': clean,
            'b_self': bs,
            'p_self': ps,
            'd_self': d,
            'b_incl': b_incl,
            'p_incl': p_incl,
            'b_calls': b_calls,
            'p_calls': p_calls,
        })
    return diff_rows

def format_delta_badge(diff, pct):
    if diff == 0:
        return "0.00% ⚪"
    badge = "🟢" if diff < 0 else "🔴"
    return f"{pct:+.2f}% {badge}"

def format_comparison_ascii(b_data, p_data, b_file, p_file):
    b_total, b_self, b_call, b_counts, b_callers = b_data
    p_total, p_self, p_call, p_counts, p_callers = p_data

    diff_total = p_total - b_total
    pct_total = (diff_total / b_total * 100) if b_total else 0.0

    b_flushes = extract_flush_calls(b_counts)
    p_flushes = extract_flush_calls(p_counts)
    d_flushes = p_flushes - b_flushes

    b_memcpy = extract_subsystem_ir(b_callers, 'memcpy')
    p_memcpy = extract_subsystem_ir(p_callers, 'memcpy')
    d_memcpy = p_memcpy - b_memcpy
    pct_memcpy = (d_memcpy / b_memcpy * 100) if b_memcpy else 0.0

    b_memset = extract_subsystem_ir(b_callers, 'memset')
    p_memset = extract_subsystem_ir(p_callers, 'memset')
    d_memset = p_memset - b_memset
    pct_memset = (d_memset / b_memset * 100) if b_memset else 0.0

    diff_rows = compute_function_diffs(b_self, b_call, b_counts, p_self, p_call, p_counts)

    out = []
    out.append("=" * 110)
    out.append("⚡ AppendFS Benchmark & Instruction Delta Report")
    out.append("=" * 110)
    out.append(f"Base Profile: {b_file}")
    out.append(f"PR Profile:   {p_file}")
    out.append("-" * 110)
    out.append(f"{'Metric':<28}  {'Base':>16}  {'PR':>16}  {'Delta':>16}  {'Change':>14}")
    out.append("-" * 110)
    status_total = "[improved]" if diff_total < 0 else ("[regressed]" if diff_total > 0 else "[unchanged]")
    out.append(f"{'Total Instructions (Ir)':<28}  {b_total:16,}  {p_total:16,}  {diff_total:+16,}  {pct_total:+8.2f}% {status_total}")
    out.append(f"{'Flushes Executed':<28}  {b_flushes:16,}  {p_flushes:16,}  {d_flushes:+16,}  {d_flushes:+8d}")
    out.append(f"{'Memory Copy (memcpy)':<28}  {b_memcpy:16,}  {p_memcpy:16,}  {d_memcpy:+16,}  {pct_memcpy:+8.2f}%")
    out.append(f"{'Memory Zeroing (memset)':<28}  {b_memset:16,}  {p_memset:16,}  {d_memset:+16,}  {pct_memset:+8.2f}%")
    out.append("=" * 110)

    # Regressions
    regressions = [r for r in diff_rows if r['d_self'] > 0]
    regressions.sort(key=lambda x: x['d_self'], reverse=True)
    if regressions:
        out.append("\n--- TOP FUNCTION REGRESSIONS (INCREASED IR) ---")
        out.append(f"{'Delta Ir':>14}  {'Delta %':>9}  {'Base Ir':>14}  {'PR Ir':>14}  {'PR Self %':>10}  Function")
        out.append("-" * 110)
        for r in regressions[:15]:
            pct = (r['d_self'] / r['b_self'] * 100) if r['b_self'] else float('inf')
            pct_str = f"{pct:+8.2f}%" if r['b_self'] else "     NEW"
            pr_pct = (r['p_self'] / p_total * 100) if p_total else 0.0
            out.append(f"{r['d_self']:+14,}  {pct_str:>9}  {r['b_self']:14,}  {r['p_self']:14,}  {pr_pct:9.2f}%  {r['name'][:42]}")

    # Improvements
    improvements = [r for r in diff_rows if r['d_self'] < 0]
    improvements.sort(key=lambda x: x['d_self'])
    if improvements:
        out.append("\n--- TOP FUNCTION IMPROVEMENTS (REDUCED IR) ---")
        out.append(f"{'Delta Ir':>14}  {'Delta %':>9}  {'Base Ir':>14}  {'PR Ir':>14}  {'PR Self %':>10}  Function")
        out.append("-" * 110)
        for r in improvements[:15]:
            pct = (r['d_self'] / r['b_self'] * 100) if r['b_self'] else -100.0
            pct_str = f"{pct:+8.2f}%" if r['p_self'] else " REMOVED"
            pr_pct = (r['p_self'] / p_total * 100) if p_total else 0.0
            out.append(f"{r['d_self']:+14,}  {pct_str:>9}  {r['b_self']:14,}  {r['p_self']:14,}  {pr_pct:9.2f}%  {r['name'][:42]}")

    # Top Hotspots in PR
    hotspots = sorted(diff_rows, key=lambda x: x['p_self'], reverse=True)[:25]
    out.append("\n--- TOP 25 HOTSPOT FUNCTIONS IN PR ---")
    out.append(f"{'PR Self Ir':>14}  {'Base Self Ir':>14}  {'Delta Ir':>14}  {'Delta %':>9}  {'PR Self %':>10}  Function")
    out.append("-" * 110)
    for r in hotspots:
        pct = (r['d_self'] / r['b_self'] * 100) if r['b_self'] else (0.0 if r['p_self'] == 0 else float('inf'))
        pct_str = f"{pct:+8.2f}%" if r['b_self'] else ("   0.00%" if r['d_self'] == 0 else "     NEW")
        pr_pct = (r['p_self'] / p_total * 100) if p_total else 0.0
        out.append(f"{r['p_self']:14,}  {r['b_self']:14,}  {r['d_self']:+14,}  {pct_str:>9}  {pr_pct:9.2f}%  {r['name'][:42]}")

    out.append("")
    return "\n".join(out)

